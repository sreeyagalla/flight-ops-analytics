"""Generate docs/DATA_DICTIONARY.md from the semantic layer and the live warehouse schema,
so documentation is derived from code instead of hand-maintained."""
import duckdb

from . import config
from .metrics import DIMENSIONS, METRICS, MIN_GROUP_FLIGHTS

TABLES = ["fct_flights", "mart_daily_origin", "mart_daily_weather", "dq_results", "pipeline_runs"]


def render(con) -> str:
    out = ["# Data dictionary", "", "_Generated by `python -m aeng.docgen`; do not edit by hand._", "",
           "## Metrics", "", "| Key | Label | Definition | SQL |", "|---|---|---|---|"]
    for m in METRICS.values():
        out.append(f"| `{m.key}` | {m.label} | {m.definition} | `{m.sql}` |")
    out += ["", f"Grouped answers exclude groups with fewer than {MIN_GROUP_FLIGHTS} flights.", "",
            "## Dimensions", "", "| Key | Description |", "|---|---|"]
    out += [f"| `{k}` | {v[2]} |" for k, v in DIMENSIONS.items()]
    out += ["", "## Tables", ""]
    for t in TABLES:
        n = con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
        cols = con.execute("SELECT column_name, data_type FROM information_schema.columns "
                           "WHERE table_name = ? ORDER BY ordinal_position", [t]).fetchall()
        out += [f"### `{t}` ({n:,} rows)", "", "| Column | Type |", "|---|---|"]
        out += [f"| `{c}` | {d} |" for c, d in cols] + [""]
    return "\n".join(out)


def main() -> None:
    con = duckdb.connect(str(config.DB_PATH), read_only=True)
    path = config.ROOT / "docs" / "DATA_DICTIONARY.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text(render(con), encoding="utf-8")
    print("wrote", path)


if __name__ == "__main__":
    main()
